"""Private file storage (Phase 9, task 9-02, PLAN Q-9-9; A27).

One small interface, two drivers:

* ``LocalStorage`` — a folder on the server: development, tests and a single-server install;
* ``S3Storage`` — any S3-compatible store (AWS S3, Cloudflare R2, Backblaze B2, MinIO), chosen
  at the production-readiness gate; credentials only in settings.

Keys are generated by AdVegaX (``new_key``), never taken from a user: lower-case letters,
digits, ``/``, ``-``, ``_`` and one extension, no ``..``. Everything is private — files are only
read back by the API for a signed-in member of the organization that owns them. Nothing is
deleted by the application (assets are archived).
"""

from __future__ import annotations

import os
import re
import secrets
import tempfile
import uuid
from pathlib import Path
from typing import Any, Protocol

KEY = re.compile(r"^[a-z0-9][a-z0-9/_-]{0,200}\.(jpg|png|webp)$")
EXTENSIONS = {"image/jpeg": "jpg", "image/png": "png", "image/webp": "webp"}


class StorageError(Exception):
    """The store could not keep or return a file (never carries credentials)."""


def new_key(organization_id: uuid.UUID, content_type: str) -> str:
    """A random key under the organization's own prefix."""
    return f"org/{organization_id}/assets/{secrets.token_hex(16)}.{EXTENSIONS[content_type]}"


def checked(key: str) -> str:
    if not KEY.fullmatch(key) or ".." in key or "//" in key:
        raise StorageError("invalid_key")
    return key


class Storage(Protocol):
    def put(self, key: str, data: bytes, content_type: str) -> None: ...

    def get(self, key: str) -> bytes: ...


class LocalStorage:
    def __init__(self, root: str | os.PathLike[str]) -> None:
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / checked(key)).resolve()
        if self.root not in path.parents:
            raise StorageError("invalid_key")  # pragma: no cover - the key pattern prevents it
        return path

    def put(self, key: str, data: bytes, content_type: str) -> None:  # noqa: ARG002
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        # Write to a temporary file and move it into place: never a half-written file.
        fd, temp = tempfile.mkstemp(dir=path.parent, prefix=".upload-")
        try:
            with os.fdopen(fd, "wb") as out:
                out.write(data)
            os.chmod(temp, 0o600)
            os.replace(temp, path)
        except BaseException:
            Path(temp).unlink(missing_ok=True)
            raise

    def get(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except FileNotFoundError as exc:
            raise StorageError("not_found") from exc


class S3Storage:
    """An S3-compatible bucket through boto3's client (``put_object``, ``get_object``)."""

    def __init__(self, client: Any, bucket: str) -> None:
        self._client = client
        self._bucket = bucket

    def put(self, key: str, data: bytes, content_type: str) -> None:
        try:
            self._client.put_object(
                Bucket=self._bucket, Key=checked(key), Body=data, ContentType=content_type
            )
        except StorageError:
            raise
        except Exception as exc:  # botocore errors: never their text (it can name the bucket)
            raise StorageError("store_failed") from exc

    def get(self, key: str) -> bytes:
        try:
            answer = self._client.get_object(Bucket=self._bucket, Key=checked(key))
            return bytes(answer["Body"].read())
        except StorageError:
            raise
        except Exception as exc:
            raise StorageError("not_found") from exc


def s3_client(settings: Any) -> Any:  # pragma: no cover - needs a real store (production gate)
    import boto3  # local import: only an S3 install loads it

    return boto3.client(
        "s3",
        endpoint_url=settings.S3_ENDPOINT_URL,
        region_name=settings.S3_REGION,
        aws_access_key_id=settings.S3_ACCESS_KEY_ID.get_secret_value(),
        aws_secret_access_key=settings.S3_SECRET_ACCESS_KEY.get_secret_value(),
    )


def build_storage(settings: Any) -> Storage:
    if settings.STORAGE_BACKEND == "s3":  # pragma: no cover - production gate
        return S3Storage(s3_client(settings), settings.S3_BUCKET)
    return LocalStorage(settings.STORAGE_LOCAL_ROOT)
